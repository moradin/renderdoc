rdcstr WrappedD3DDevice9::WriteSurface(IDirect3DSurface9 *surf, const D3D9SubresourceData &sub)
{
  if(sub.Data.empty())
    return rdcstr();

  D3DSURFACE_DESC desc = {};
  surf->GetDesc(&desc);

  if((desc.Usage & D3DUSAGE_DEPTHSTENCIL) && !IsLockableDepth(desc.Format))
    return WriteDepthStencil(surf, sub);

  const bool whole = sub.X == 0 && sub.Y == 0 && sub.Width == desc.Width && sub.Height == desc.Height;
  RECT rect = {(LONG)sub.X, (LONG)sub.Y, LONG(sub.X + sub.Width), LONG(sub.Y + sub.Height)};

  // anything that can be locked: system memory, dynamic textures, lockable render targets
  if(desc.MultiSampleType == D3DMULTISAMPLE_NONE)
  {
    D3DLOCKED_RECT locked = {};
    if(SUCCEEDED(surf->LockRect(&locked, whole ? NULL : &rect, 0)) && locked.pBits)
    {
      CopyToLocked(sub, (byte *)locked.pBits,
                   D3D9LockedRowPitch(desc.Format, desc.Width, (uint32_t)locked.Pitch), 0);
      surf->UnlockRect();
      return rdcstr();
    }
  }

  // otherwise copy from system memory, through a render target if this is multisampled
  IDirect3DSurface9 *sysmem = NULL, *temp = NULL;
  rdcstr err;

  HRESULT hr = m_device->CreateOffscreenPlainSurface(sub.Width, sub.Height, desc.Format,
                                                     D3DPOOL_SYSTEMMEM, &sysmem, NULL);
  if(SUCCEEDED(hr))
  {
    D3DLOCKED_RECT locked = {};
    hr = sysmem->LockRect(&locked, NULL, 0);
    if(SUCCEEDED(hr))
    {
      CopyToLocked(sub, (byte *)locked.pBits,
                   D3D9LockedRowPitch(desc.Format, sub.Width, (uint32_t)locked.Pitch), 0);
      sysmem->UnlockRect();
    }
  }

  if(SUCCEEDED(hr))
  {
    POINT pt = {(LONG)sub.X, (LONG)sub.Y};
    if(desc.MultiSampleType == D3DMULTISAMPLE_NONE)
    {
      hr = m_device->UpdateSurface(sysmem, NULL, surf, &pt);
    }
    else
    {
      hr = m_device->CreateRenderTarget(sub.Width, sub.Height, desc.Format, D3DMULTISAMPLE_NONE, 0,
                                        FALSE, &temp, NULL);
      if(SUCCEEDED(hr))
        hr = m_device->UpdateSurface(sysmem, NULL, temp, NULL);
      if(SUCCEEDED(hr))
        hr = m_device->StretchRect(temp, NULL, surf, &rect, D3DTEXF_NONE);
    }
  }

  if(FAILED(hr))
    err = StringFormat::Fmt("Couldn't write %s contents: %s", ToStr(desc.Format).c_str(),
                            ToStr(hr).c_str());

  SAFE_RELEASE(temp);
  SAFE_RELEASE(sysmem);
  return err;
}

rdcstr WrappedD3DDevice9::WriteVolume(IDirect3DVolume9 *vol, const D3D9SubresourceData &sub)
{
  if(sub.Data.empty())
    return rdcstr();

  D3DBOX box = {sub.X, sub.Y, sub.X + sub.Width, sub.Y + sub.Height, sub.Z, sub.Z + sub.Depth};
  D3DLOCKED_BOX locked = {};
  HRESULT hr = vol->LockBox(&locked, &box, 0);
  if(FAILED(hr) || locked.pBits == NULL)
    return StringFormat::Fmt("Couldn't lock the volume to write its contents: %s", ToStr(hr).c_str());

  CopyToLocked(sub, (byte *)locked.pBits, (uint32_t)locked.RowPitch, (uint32_t)locked.SlicePitch);
  vol->UnlockBox();
  return rdcstr();
}

void WrappedD3DDevice9::WriteContents(WrappedD3D9Object *obj, const D3D9SubresourceData &sub)
{
  if(obj == NULL)
    return;

  rdcstr err;

  switch(obj->GetResourceType())
  {
    case Resource_VertexBuffer:
    case Resource_IndexBuffer:
    {
      const bool vb = obj->GetResourceType() == Resource_VertexBuffer;
      void *data = NULL;
      HRESULT hr = vb ? ((WrappedD3DVertexBuffer9 *)obj)->GetReal()->Lock(sub.X, sub.Width, &data, 0)
                      : ((WrappedD3DIndexBuffer9 *)obj)->GetReal()->Lock(sub.X, sub.Width, &data, 0);
      if(FAILED(hr) || data == NULL)
      {
        err = StringFormat::Fmt("Couldn't lock the buffer: %s", ToStr(hr).c_str());
        break;
      }
      memcpy(data, sub.Data.data(), RDCMIN((size_t)sub.Width, sub.Data.size()));
      if(vb)
        ((WrappedD3DVertexBuffer9 *)obj)->GetReal()->Unlock();
      else
        ((WrappedD3DIndexBuffer9 *)obj)->GetReal()->Unlock();
      break;
    }
    case Resource_Texture:
    {
      IDirect3DSurface9 *surf = NULL;
      if(SUCCEEDED(((WrappedD3DTexture9 *)obj)->GetReal()->GetSurfaceLevel(sub.Level, &surf)) && surf)
      {
        err = WriteSurface(surf, sub);
        surf->Release();
      }
      break;
    }
    case Resource_CubeTexture:
    {
      IDirect3DSurface9 *surf = NULL;
      if(SUCCEEDED(((WrappedD3DCubeTexture9 *)obj)
                       ->GetReal()
                       ->GetCubeMapSurface((D3DCUBEMAP_FACES)sub.Face, sub.Level, &surf)) &&
         surf)
      {
        err = WriteSurface(surf, sub);
        surf->Release();
      }
      break;
    }
    case Resource_VolumeTexture:
    {
      IDirect3DVolume9 *vol = NULL;
      if(SUCCEEDED(((WrappedD3DVolumeTexture9 *)obj)->GetReal()->GetVolumeLevel(sub.Level, &vol)) &&
         vol)
      {
        err = WriteVolume(vol, sub);
        vol->Release();
      }
      break;
    }
    case Resource_Surface: err = WriteSurface(((WrappedD3DSurface9 *)obj)->GetReal(), sub); break;
    case Resource_Volume: err = WriteVolume(((WrappedD3DVolume9 *)obj)->GetReal(), sub); break;
    default: break;
  }

  if(!err.empty())
    RDCWARN("Couldn't write the contents of %s: %s", ToStr(obj->GetResourceID()).c_str(),
            err.c_str());
}

///////////////////////////////////////////////////////////////////////////////
// reading contents for the replay controller

rdcstr WrappedD3DDevice9::ReadSubresource(WrappedD3D9Object *obj, uint32_t face, uint32_t level,
                                          D3D9SubresourceData &sub)
{
  if(obj == NULL)
    return "Unknown object";

  switch(obj->GetResourceType())
  {
    case Resource_VertexBuffer:
    case Resource_IndexBuffer:
    {
      const bool vb = obj->GetResourceType() == Resource_VertexBuffer;
      UINT size = 0;
      if(vb)
      {
        D3DVERTEXBUFFER_DESC desc = {};
        ((WrappedD3DVertexBuffer9 *)obj)->GetReal()->GetDesc(&desc);
        size = desc.Size;
      }
      else
      {
        D3DINDEXBUFFER_DESC desc = {};
        ((WrappedD3DIndexBuffer9 *)obj)->GetReal()->GetDesc(&desc);
        size = desc.Size;
      }

      void *data = NULL;
      HRESULT hr =
          vb ? ((WrappedD3DVertexBuffer9 *)obj)->GetReal()->Lock(0, 0, &data, D3DLOCK_READONLY)
             : ((WrappedD3DIndexBuffer9 *)obj)->GetReal()->Lock(0, 0, &data, D3DLOCK_READONLY);
      if(FAILED(hr) || data == NULL)
        return StringFormat::Fmt("Couldn't lock the buffer: %s", ToStr(hr).c_str());

      sub.Width = size;
      D3D9CopyFromLocked(sub, D3DFMT_VERTEXDATA, data, size, size);

      if(vb)
        ((WrappedD3DVertexBuffer9 *)obj)->GetReal()->Unlock();
      else
        ((WrappedD3DIndexBuffer9 *)obj)->GetReal()->Unlock();
      return rdcstr();
    }
    case Resource_Texture:
    case Resource_CubeTexture:
    case Resource_Surface:
    {
      IDirect3DSurface9 *surf = NULL;
      if(obj->GetResourceType() == Resource_Texture)
        ((WrappedD3DTexture9 *)obj)->GetReal()->GetSurfaceLevel(level, &surf);
      else if(obj->GetResourceType() == Resource_CubeTexture)
        ((WrappedD3DCubeTexture9 *)obj)->GetReal()->GetCubeMapSurface((D3DCUBEMAP_FACES)face, level, &surf);
      else
        (surf = ((WrappedD3DSurface9 *)obj)->GetReal())->AddRef();

      if(surf == NULL)
        return "Couldn't get the surface";

      D3DSURFACE_DESC desc = {};
      surf->GetDesc(&desc);

      rdcstr err;
      if((desc.Usage & D3DUSAGE_DEPTHSTENCIL) && !IsLockableDepth(desc.Format))
      {
        rdcstr note;
        err = ReadDepthStencil(surf, sub, note);
      }
      else
      {
        err = D3D9ReadSurfaceContents(m_device, surf, sub);
      }

      surf->Release();
      return err;
    }
    case Resource_VolumeTexture:
    {
      IDirect3DVolume9 *vol = NULL;
      ((WrappedD3DVolumeTexture9 *)obj)->GetReal()->GetVolumeLevel(level, &vol);
      if(vol == NULL)
        return "Couldn't get the volume level";

      D3DVOLUME_DESC desc = {};
      vol->GetDesc(&desc);

      D3DLOCKED_BOX locked = {};
      HRESULT hr = vol->LockBox(&locked, NULL, D3DLOCK_READONLY);
      if(FAILED(hr) || locked.pBits == NULL)
      {
        vol->Release();
        return StringFormat::Fmt("Couldn't lock the volume: %s", ToStr(hr).c_str());
      }

      sub.Width = desc.Width;
      sub.Height = desc.Height;
      sub.Depth = desc.Depth;
      D3D9CopyFromLocked(sub, desc.Format, locked.pBits, (uint32_t)locked.RowPitch,
                         (uint32_t)locked.SlicePitch);

      vol->UnlockBox();
      vol->Release();
      return rdcstr();
    }
    default: return "Object has no contents";
  }
}
