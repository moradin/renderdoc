// copies sub's rows to a locked subresource
void CopyToLocked(const D3D9SubresourceData &sub, byte *dst, uint32_t dstRowPitch,
                  uint32_t dstSlicePitch)
{
  const size_t srcSlicePitch = size_t(sub.RowPitch) * sub.RowCount;
  const uint32_t copyBytes = RDCMIN(sub.RowPitch, dstRowPitch);

  for(uint32_t z = 0; z < sub.Depth; z++)
  {
    for(uint32_t r = 0; r < sub.RowCount; r++)
    {
      const size_t srcOffs = z * srcSlicePitch + size_t(r) * sub.RowPitch;
      if(srcOffs + copyBytes > sub.Data.size())
        return;
      memcpy(dst + size_t(z) * dstSlicePitch + size_t(r) * dstRowPitch, sub.Data.data() + srcOffs,
             copyBytes);
    }
  }
}

bool IsLockableDepth(D3DFORMAT format)
{
  return format == D3DFMT_D16_LOCKABLE || format == D3DFMT_D32F_LOCKABLE ||
         format == D3DFMT_D32_LOCKABLE || format == D3DFMT_S8_LOCKABLE;
}
