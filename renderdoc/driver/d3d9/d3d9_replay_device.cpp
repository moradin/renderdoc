RDResult WrappedD3DDevice9::ReadLogInitialisation(RDCFile *rdc, bool storeStructuredBuffers)
{
  int sectionIdx = rdc->SectionIndex(SectionType::FrameCapture);

  if(sectionIdx < 0)
    RETURN_ERROR_RESULT(ResultCode::FileCorrupted, "File does not contain captured API data");

  StreamReader *reader = rdc->ReadSection(sectionIdx);

  if(IsStructuredExporting(m_State))
  {
    // no timebase conversion when exporting
    m_TimeBase = 0;
    m_TimeFrequency = 1.0;
  }
  else
  {
    m_TimeBase = rdc->GetTimestampBase();
    m_TimeFrequency = rdc->GetTimestampFrequency();
  }

  if(reader->IsErrored())
  {
    RDResult result = reader->GetError();
    delete reader;
    return result;
  }

  ReadSerialiser ser(reader, Ownership::Stream);

  ser.SetStringDatabase(&m_StringDB);
  ser.SetUserData(m_ResourceManager);

  ser.ConfigureStructuredExport(&GetChunkName, storeStructuredBuffers, m_TimeBase, m_TimeFrequency);

  m_StructuredFile = &ser.GetStructuredFile();

  m_StoredStructuredData->version = m_StructuredFile->version = m_SectionVersion;

  ser.SetVersion(m_SectionVersion);

  uint64_t frameDataSize = 0;
  uint64_t initDataSize = 0;

  for(;;)
  {
    uint64_t offsetStart = reader->GetOffset();

    D3D9Chunk chunk = ser.ReadChunk<D3D9Chunk>();

    if(reader->IsErrored())
      return RDResult(ResultCode::APIDataCorrupted, ser.GetError().message);

    bool success = ProcessChunk(ser, chunk);

    ser.EndChunk();

    if(reader->IsErrored())
      return RDResult(ResultCode::APIDataCorrupted, ser.GetError().message);

    if(!success)
    {
      if(m_FailedReplayResult == ResultCode::Succeeded)
        RETURN_ERROR_RESULT(ResultCode::APIReplayFailed, "Failed to process chunk %s",
                            GetChunkName((uint32_t)chunk).c_str());
      return m_FailedReplayResult;
    }

    uint64_t offsetEnd = reader->GetOffset();

    if((SystemChunk)chunk == SystemChunk::InitialContents)
      initDataSize += offsetEnd - offsetStart;

    RenderDoc::Inst().SetProgress(LoadProgress::FileInitialRead,
                                  float(offsetEnd) / float(reader->GetSize()));

    if((SystemChunk)chunk == SystemChunk::CaptureScope)
    {
      if(m_Replay)
        m_Replay->WriteFrameRecord().frameInfo.fileOffset = offsetStart;

      // the rest is the frame, which is kept in memory to replay again and again
      frameDataSize = reader->GetSize() - reader->GetOffset();
      m_FrameReader = new StreamReader(reader, frameDataSize);

      if(IsReplayMode(m_State))
        m_ResourceManager->ApplyInitialContents();

      RDResult status = ContextReplayLog(m_State, 0, 0, false);

      if(status != ResultCode::Succeeded)
        return status;

      break;
    }

    if(reader->AtEnd())
      break;
  }

  // steal the structured data for ourselves
  m_StructuredFile->Swap(*m_StoredStructuredData);

  // and in future use this file.
  m_StructuredFile = m_StoredStructuredData;

  if(m_Replay)
  {
    FrameDescription &frameInfo = m_Replay->WriteFrameRecord().frameInfo;
    frameInfo.uncompressedFileSize = rdc->GetSectionProperties(sectionIdx).uncompressedSize;
    frameInfo.compressedFileSize = rdc->GetSectionProperties(sectionIdx).compressedSize;
    frameInfo.persistentSize = frameDataSize;
    frameInfo.initDataSize = initDataSize;
  }

  return ResultCode::Succeeded;
}

RDResult WrappedD3DDevice9::ContextReplayLog(CaptureState readType, uint32_t startEventID,
                                             uint32_t endEventID, bool partial)
{
  if(m_FrameReader == NULL)
    return ResultCode::Succeeded;

  m_FrameReader->SetOffset(0);

  ReadSerialiser ser(m_FrameReader, Ownership::Nothing);

  ser.SetStringDatabase(&m_StringDB);
  ser.SetUserData(m_ResourceManager);
  ser.SetVersion(m_SectionVersion);

  SDFile *prevFile = m_StructuredFile;

  if(IsLoading(m_State) || IsStructuredExporting(m_State))
  {
    ser.ConfigureStructuredExport(&GetChunkName, IsStructuredExporting(m_State), m_TimeBase,
                                  m_TimeFrequency);

    ser.GetStructuredFile().Swap(*m_StructuredFile);

    m_StructuredFile = &ser.GetStructuredFile();
  }

  // the frame starts with the device's state
  D3D9Chunk header = ser.ReadChunk<D3D9Chunk>();
  if(header != D3D9Chunk::BeginCaptureFrame)
  {
    if(IsLoading(m_State) || IsStructuredExporting(m_State))
      ser.GetStructuredFile().Swap(*prevFile);
    m_StructuredFile = prevFile;
    RETURN_ERROR_RESULT(ResultCode::FileCorrupted,
                        "The frame doesn't start with BeginCaptureFrame");
  }

  if(partial)
    ser.SkipCurrentChunk();
  else
    Serialise_BeginCaptureFrame(ser);

  ser.EndChunk();

  m_CurEvents.clear();

  if(IsActiveReplaying(m_State))
  {
    APIEvent ev = GetEvent(startEventID);
    m_CurEventID = ev.eventId;
    if(partial)
      ser.GetReader()->SetOffset(ev.fileOffset);
    m_FirstEventID = startEventID;
    m_LastEventID = endEventID;
  }
  else
  {
    m_CurEventID = 1;
    m_CurActionID = 1;
    m_FirstEventID = 0;
    m_LastEventID = ~0U;

    m_ParentAction = ActionDescription();
    m_ActionStack.clear();
    m_ActionStack.push_back(&m_ParentAction);
    m_Events.clear();
  }

  const uint64_t startOffset = ser.GetReader()->GetOffset();

  for(;;)
  {
    if(IsActiveReplaying(m_State) && m_CurEventID > endEventID)
      break;

    if(ser.GetReader()->AtEnd())
      break;

    m_CurChunkOffset = ser.GetReader()->GetOffset();

    D3D9Chunk chunk = ser.ReadChunk<D3D9Chunk>();

    if(ser.GetReader()->IsErrored())
      return RDResult(ResultCode::APIDataCorrupted, ser.GetError().message);

    bool success = ContextProcessChunk(ser, chunk);

    ser.EndChunk();

    if(ser.GetReader()->IsErrored())
      return RDResult(ResultCode::APIDataCorrupted, ser.GetError().message);

    if(!success)
    {
      if(m_FailedReplayResult == ResultCode::Succeeded)
        RETURN_ERROR_RESULT(ResultCode::APIReplayFailed, "Failed to replay chunk %s",
                            GetChunkName((uint32_t)chunk).c_str());
      return m_FailedReplayResult;
    }

    RenderDoc::Inst().SetProgress(
        LoadProgress::FrameEventsRead,
        float(m_CurChunkOffset - startOffset) / float(ser.GetReader()->GetSize()));

    m_LastChunk = chunk;
    m_CurEventID++;
  }

  if(IsLoading(m_State))
  {
    // calls after the last action, e.g. when the application ended the capture itself without
    // presenting
    if(!m_CurEvents.empty())
    {
      ActionDescription action;
      action.customName = "End of Capture";
      action.flags = ActionFlags::Present;
      action.eventId = m_CurEvents.back().eventId;
      action.actionId = m_CurActionID++;
      action.events.swap(m_CurEvents);
      m_ParentAction.children.push_back(action);
    }

    m_Replay->WriteFrameRecord().actionList = m_ParentAction.children;
    SetupActionPointers(m_Actions, m_Replay->WriteFrameRecord().actionList);
  }

  // swap the structure back now that we've accumulated the frame as well.
  if(IsLoading(m_State) || IsStructuredExporting(m_State))
    ser.GetStructuredFile().Swap(*prevFile);

  m_StructuredFile = prevFile;

  return ResultCode::Succeeded;
}

bool WrappedD3DDevice9::ContextProcessChunk(ReadSerialiser &ser, D3D9Chunk chunk)
{
  m_AddedAction = false;

  bool success = ProcessChunk(ser, chunk);

  if(!success)
    return false;

  if(IsLoading(m_State))
  {
    if(chunk == D3D9Chunk::D3DPERF_BeginEvent)
    {
      // push down the action stack to the marker just added
      m_ActionStack.push_back(&m_ActionStack.back()->children.back());
    }
    else if(chunk == D3D9Chunk::D3DPERF_EndEvent)
    {
      // refuse to pop off further than the root action (mismatched begin/end events)
      if(m_ActionStack.size() > 1)
        m_ActionStack.pop_back();
    }

    if(!m_AddedAction)
      AddEvent();
  }

  m_AddedAction = false;

  return true;
}

void WrappedD3DDevice9::AddEvent()
{
  APIEvent apievent;

  apievent.fileOffset = m_CurChunkOffset;
  apievent.eventId = m_CurEventID;
  apievent.chunkIndex = uint32_t(m_StructuredFile->chunks.size() - 1);

  m_CurEvents.push_back(apievent);

  if(IsLoading(m_State))
  {
    m_Events.resize(apievent.eventId + 1);
    m_Events[apievent.eventId] = apievent;
  }
}

void WrappedD3DDevice9::AddAction(const ActionDescription &a)
{
  m_AddedAction = true;

  ActionDescription action = a;
  action.eventId = m_CurEventID;
  action.actionId = m_CurActionID;

  for(uint32_t i = 0; i < D3D9_NUM_RENDER_TARGETS && i < action.outputs.size(); i++)
    action.outputs[i] = SurfaceTextureID(m_RenderTargets[i]);
  action.depthOut = SurfaceTextureID(m_DepthStencil);

  // markers don't increment action ID
  const ActionFlags markerMask = ActionFlags::SetMarker | ActionFlags::PushMarker |
                                 ActionFlags::PopMarker | ActionFlags::MultiAction;
  if(!(action.flags & markerMask))
    m_CurActionID++;

  action.events.swap(m_CurEvents);

  if(!m_ActionStack.empty())
    m_ActionStack.back()->children.push_back(action);
  else
    RDCERR("Somehow lost action stack!");
}

void WrappedD3DDevice9::AddDrawAction(ActionFlags flags, uint32_t numIndices, uint32_t indexOffset,
                                      int32_t baseVertex, uint32_t vertexOffset)
{
  if(!IsLoading(m_State))
    return;

  AddEvent();

  ActionDescription action;
  action.flags = ActionFlags::Drawcall | flags;
  action.numIndices = numIndices;
  action.indexOffset = indexOffset;
  action.baseVertex = baseVertex;
  action.vertexOffset = vertexOffset;
  action.numInstances = 1;

  // instancing: stream 0's frequency is the instance count when it's indexed data
  if(m_device)
  {
    UINT freq = 1;
    if(SUCCEEDED(m_device->GetStreamSourceFreq(0, &freq)) && (freq & D3DSTREAMSOURCE_INDEXEDDATA))
    {
      action.numInstances = RDCMAX(1U, freq & 0x3FFFFFFF);
      action.flags |= ActionFlags::Instanced;
    }
  }

  AddAction(action);
}

void WrappedD3DDevice9::AddCopyAction(ActionFlags flags, IUnknown *source, IUnknown *dest)
{
  if(!IsLoading(m_State))
    return;

  AddEvent();

  ActionDescription action;
  action.flags = flags;
  action.copySource = ContentsTextureID(source);
  action.copyDestination = ContentsTextureID(dest);

  WrappedD3D9Object *src = GetWrappedObject(source);
  if(src && src->GetContainer() && src->GetContainer()->GetResourceType() != Resource_SwapChain)
    action.copySourceSubresource = Subresource(src->GetChildLevel(), src->GetChildFace());
  WrappedD3D9Object *dst = GetWrappedObject(dest);
  if(dst && dst->GetContainer() && dst->GetContainer()->GetResourceType() != Resource_SwapChain)
    action.copyDestinationSubresource = Subresource(dst->GetChildLevel(), dst->GetChildFace());

  AddAction(action);
}

const APIEvent &WrappedD3DDevice9::GetEvent(uint32_t eventId)
{
  static APIEvent empty;
  if(m_Events.empty())
    return empty;

  // start at where the requested eventId would be, and find the next valid event
  size_t idx = eventId;
  while(idx < m_Events.size() - 1 && m_Events[idx].eventId == 0)
    idx++;

  return m_Events[RDCMIN(idx, m_Events.size() - 1)];
}

const ActionDescription *WrappedD3DDevice9::GetAction(uint32_t eventId)
{
  if(eventId >= m_Actions.size())
    return NULL;

  return m_Actions[eventId];
}

void WrappedD3DDevice9::ReplayLog(uint32_t startEventID, uint32_t endEventID, ReplayLogType replayType)
{
  bool partial = true;

  if(startEventID == 0 && (replayType == eReplay_WithoutDraw || replayType == eReplay_Full))
  {
    startEventID = 1;
    partial = false;
  }

  if(!partial)
  {
    ReplayEndScene();
    m_ResourceManager->ApplyInitialContents();
  }

  m_State = CaptureState::ActiveReplaying;

  RDResult status = ResultCode::Succeeded;

  if(replayType == eReplay_Full)
    status = ContextReplayLog(m_State, startEventID, endEventID, partial);
  else if(replayType == eReplay_WithoutDraw)
    status = ContextReplayLog(m_State, startEventID, RDCMAX(1U, endEventID) - 1, partial);
  else if(replayType == eReplay_OnlyDraw)
    status = ContextReplayLog(m_State, endEventID, endEventID, partial);
  else
    RDCFATAL("Unexpected replay type");

  if(status != ResultCode::Succeeded)
    RDCERR("Replay failed: %s", status.message.c_str());

  // whatever reads the results next (copies, locks) shouldn't be inside a scene. A partial replay
  // that draws starts another one.
  ReplayEndScene();
}

