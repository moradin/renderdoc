void WrappedD3DDevice9::AddReplayResource(ResourceId id, ResourceType type, const char *prefix)
{
  if(m_Replay == NULL || id == ResourceId())
    return;

  ResourceDescription &descr = m_Replay->GetResourceDesc(id);

  uint64_t num;
  memcpy(&num, &id, sizeof(uint64_t));
  descr.name = StringFormat::Fmt("%s %llu", prefix, num);
  descr.autogeneratedName = true;
  descr.type = type;
  descr.initialisationChunks.push_back((uint32_t)m_StructuredFile->chunks.size() - 1);
}

void WrappedD3DDevice9::DerivedReplayResource(ResourceId parent, ResourceId child)
{
  if(m_Replay == NULL || parent == ResourceId() || child == ResourceId())
    return;

  ResourceDescription &p = m_Replay->GetResourceDesc(parent);
  if(p.derivedResources.contains(child))
    return;

  p.derivedResources.push_back(child);
  m_Replay->GetResourceDesc(child).parentResources.push_back(parent);
}

bool WrappedD3DDevice9::CheckReplayCreate(HRESULT hr, IUnknown *obj, ResourceId id, const char *what)
{
  if(FAILED(hr) || obj == NULL)
  {
    SET_ERROR_RESULT(m_FailedReplayResult, ResultCode::APIReplayFailed,
                     "Failed creating %s %s, HRESULT: %s", what, ToStr(id).c_str(),
                     ToStr(hr).c_str());
    return false;
  }

  m_ReplayObjects.push_back(obj);

  if(GetResID(obj) != id)
    RDCERR("%s %s was created as %s", what, ToStr(id).c_str(), ToStr(GetResID(obj)).c_str());

  return true;
}

void WrappedD3DDevice9::PatchReplayPresentParams(D3DPRESENT_PARAMETERS &params)
{
  // nothing is presented, but swapchains still need a window
  params.Windowed = TRUE;
  params.hDeviceWindow = m_ReplayWindow;
  params.FullScreen_RefreshRateInHz = 0;
  params.PresentationInterval = D3DPRESENT_INTERVAL_IMMEDIATE;
  // multisampled back buffers need DISCARD, and the others don't mind
  params.SwapEffect = D3DSWAPEFFECT_DISCARD;
  params.Flags &= D3DPRESENTFLAG_LOCKABLE_BACKBUFFER | D3DPRESENTFLAG_DISCARD_DEPTHSTENCIL;
  if(params.BackBufferCount == 0)
    params.BackBufferCount = 1;
  if(params.BackBufferWidth == 0)
    params.BackBufferWidth = 1;
  if(params.BackBufferHeight == 0)
    params.BackBufferHeight = 1;
}

