// Replaying a capture
// -------------------
// The replay device is a WrappedD3DDevice9 around a D3D9Ex device on a hidden window, and replays
// through the same wrapped methods the application called. Wrappers created during replay take the
// ID they had in the capture (see TakeWrapperID), so the captured IDs work everywhere.
//
// * Loading reads everything before the frame: the device-owned objects (DeviceInitialisation),
//   every object's creation, and the initial contents. The capture's implicit swapchains are
//   created as additional swapchains presenting to the hidden window, windowed, and its automatic
//   depth stencil as a standalone depth stencil.
// * D3D9Ex devices have no managed pool, so those objects are created in the default pool, and
//   textures that can't be rendered to are made dynamic where the driver allows it, so that their
//   contents can be written by locking them. Buffers lose D3DUSAGE_WRITEONLY so they can be read.
// * Replaying the frame applies the initial contents, sets the device state from
//   BeginCaptureFrame, and replays the frame's calls up to the event asked for. Present only
//   marks the end of the frame. Every call is an event; draws, clears, copies, presents and
//   D3DPERF markers are actions.

ResourceId WrappedD3DDevice9::TakeWrapperID()
{
  ResourceId ret = m_NextWrapperID;
  m_NextWrapperID = ResourceId();
  return ret != ResourceId() ? ret : ResourceIDGen::GetNewUniqueID();
}

ResourceId WrappedD3DDevice9::SurfaceTextureID(IDirect3DSurface9 *surf)
{
  WrappedD3D9Object *obj = GetWrappedObject(surf);
  if(obj == NULL)
    return ResourceId();

  WrappedD3D9Object *container = obj->GetContainer();
  if(container && container->GetResourceType() != Resource_SwapChain)
    return container->GetResourceID();

  return obj->GetResourceID();
}

ResourceId WrappedD3DDevice9::ContentsTextureID(IUnknown *obj)
{
  WrappedD3D9Object *wrapped = GetWrappedObject(obj);
  if(wrapped == NULL)
    return ResourceId();

  if(wrapped->GetResourceType() == Resource_Surface)
    return SurfaceTextureID((IDirect3DSurface9 *)obj);

  // volume levels belong to their texture
  if(wrapped->GetResourceType() == Resource_Volume && wrapped->GetContainer())
    return wrapped->GetContainer()->GetResourceID();

  return wrapped->GetResourceID();
}

ResourceId WrappedD3DDevice9::ReplayBackBufferID(IDirect3DSwapChain9 *swap)
{
  if(swap == NULL)
    return ResourceId();

  IDirect3DSurface9 *bb = NULL;
  if(FAILED(swap->GetBackBuffer(0, D3DBACKBUFFER_TYPE_MONO, &bb)) || bb == NULL)
    return ResourceId();

  ResourceId id = GetResID(bb);
  bb->Release();

  if(m_Replay && id != ResourceId())
  {
    ResourceDescription &descr = m_Replay->GetResourceDesc(id);
    if(descr.name.empty())
    {
      uint64_t num;
      memcpy(&num, &id, sizeof(uint64_t));
      descr.name = StringFormat::Fmt("Backbuffer %llu", num);
      descr.autogeneratedName = true;
      descr.type = ResourceType::SwapchainImage;
      DerivedReplayResource(GetResID(swap), id);
    }
  }

  return id;
}

SDFile *WrappedD3DDevice9::DetachStructuredFile()
{
  SDFile *ret = m_StoredStructuredData;
  m_StoredStructuredData = m_StructuredFile = NULL;
  return ret;
}

void WrappedD3DDevice9::ReleaseReplayObjects()
{
  ReplayEndScene();

  // children first: state blocks and swapchains can reference other objects
  for(int32_t i = m_ReplayObjects.count() - 1; i >= 0; i--)
    m_ReplayObjects[i]->Release();
  m_ReplayObjects.clear();
  m_ReplaySwapChains.clear();

  SAFE_DELETE(m_FrameReader);
}

RDResult WrappedD3DDevice9::FatalErrorCheck()
{
  // without a window this only reports problems with the device itself, not occlusion
  if(m_deviceEx)
  {
    HRESULT hr = m_deviceEx->CheckDeviceState(NULL);
    if(hr == D3DERR_DEVICEHUNG || hr == D3DERR_DEVICEREMOVED)
      RETURN_ERROR_RESULT(ResultCode::DeviceLost, "The D3D9 replay device stopped working: %s",
                          ToStr(hr).c_str());
  }

  return ResultCode::Succeeded;
}

