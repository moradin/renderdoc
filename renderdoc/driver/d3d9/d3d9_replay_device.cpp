void WrappedD3DDevice9::ReplayBeginScene()
{
  if(!m_ReplayInScene && m_device && SUCCEEDED(m_device->BeginScene()))
    m_ReplayInScene = true;
}

void WrappedD3DDevice9::ReplayEndScene()
{
  if(m_ReplayInScene && m_device)
    m_device->EndScene();
  m_ReplayInScene = false;
}

void WrappedD3DDevice9::ApplyReplayDeviceState(const D3D9DeviceState &state)
{
  // shader constants beyond the hardware's only exist with software vertex processing, which the
  // mixed replay device allows
  m_device->SetSoftwareVertexProcessing(state.SoftwareVertexProcessing);

  {
    SCOPED_LOCK(m_D3DLock);
    for(const D3D9LightState &l : state.Lights)
      m_LightIndices.Add(l.Index);
    for(const D3D9Palette &p : state.Palettes)
    {
      // m_PaletteNumbers must only hold palettes the device has had set: GetPaletteEntries on one
      // that never was crashes inside d3d9 (seen on a D3D9Ex mixed-VP device) rather than failing.
      // So set it here, before the fetch below asks for it.
      m_device->SetPaletteEntries(p.Number, p.Entries.data());
      m_PaletteNumbers.Add(p.Number);
    }
  }

  // only setting what differs from the device's state takes care of the state that's left out
  // when it's the default (identity world matrices, lights that were never set)
  D3D9DeviceState current;
  D3D9FetchDeviceState(m_device, m_InitParams.BehaviorFlags, m_LightIndices, m_PaletteNumbers,
                       current);
  D3D9RestoreDeviceState(m_device, state, current);
}

void WrappedD3DDevice9::ApplyStateBlockContents(WrappedD3DStateBlock9 *sb,
                                                const D3D9StateBlockContents &contents)
{
  auto res = [this](ResourceId id) -> IUnknown * {
    if(id == ResourceId() || !m_ResourceManager->HasResource(id))
      return NULL;
    return m_ResourceManager->GetResource(id);
  };

  ApplyReplayDeviceState(contents.State);

  for(size_t slot = 0; slot < contents.Textures.size() && slot < D3D9_NUM_TEXTURE_SLOTS; slot++)
    SetTexture(D3D9SlotToSampler((uint32_t)slot),
               (IDirect3DBaseTexture9 *)res(contents.Textures[slot]));

  for(size_t i = 0; i < contents.StreamSources.size() && i < D3D9_NUM_STREAMS; i++)
    SetStreamSource((UINT)i, (IDirect3DVertexBuffer9 *)res(contents.StreamSources[i]),
                    i < contents.StreamOffsets.size() ? contents.StreamOffsets[i] : 0,
                    i < contents.StreamStrides.size() ? contents.StreamStrides[i] : 0);

  SetIndices((IDirect3DIndexBuffer9 *)res(contents.Indices));
  SetVertexShader((IDirect3DVertexShader9 *)res(contents.VertexShader));
  SetPixelShader((IDirect3DPixelShader9 *)res(contents.PixelShader));
  if(contents.DeclarationFromFVF)
    SetFVF(contents.State.FVF);
  else
    SetVertexDeclaration((IDirect3DVertexDeclaration9 *)res(contents.VertexDeclaration));

  sb->Capture();
}

