# Writes the unit test data header from d3dx_probe.py's and setdefaults_probe.py's outputs.
# usage: python gen_header.py <dir> <out .h> name...
import json, os, struct, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from shaders import SHADERS

d = sys.argv[1]
outpath = sys.argv[2]
names = sys.argv[3:]
dx = json.load(open(os.path.join(d, 'd3dx.json')))
sd = json.load(open(os.path.join(d, 'setdefaults.json')))
profiles = {n: (p, legacy) for n, _, p, legacy in SHADERS}
SETS = {'B': 0, 'I': 1, 'F': 2}

LICENSE_FROM = os.path.join(os.path.dirname(os.path.abspath(outpath)), 'd3d9_bytecode_test.h')
lines = open(LICENSE_FROM).read().split(chr(10))[:23]
w = lines.append
w('')
w('// Generated by the probe in test_reports/d3d9_ctab_check/ from shaders compiled by')
w('// D3DCompile (d3dcompiler_47) and the legacy D3DX9 compiler (d3dx9_31, for 1_x), with the')
w('// expected values from D3DX9_43\'s ID3DXConstantTable: GetConstantDesc for every constant,')
w('// member and array element, and SetDefaults\' registers read back from a device.')
w('')
w('#pragma once')
w('')
w('namespace CTABTestData')
w('{')
w('struct Node')
w('{')
w('  const char *path;')
w('  uint16_t set, reg, count, cls, type, rows, columns, elements, members;')
w('};')
w('')
w('struct Register')
w('{')
w('  // D3DXREGISTER_SET: 0 bool, 1 int4, 2 float4. Bool registers only use value[0]')
w('  uint16_t set, reg;')
w('  uint32_t value[4];')
w('};')
w('')
w('struct Shader')
w('{')
w('  const char *name;')
w('  uint32_t version;')
w('  const uint32_t *ctab;')
w('  uint32_t ctabDWORDs;')
w('  const Node *nodes;')
w('  size_t numNodes;')
w('  const Register *regs;')
w('  size_t numRegs;')
w('};')
w('')

for name in names:
    code = open(os.path.join(d, name + '.bin'), 'rb').read()
    words = struct.unpack('<%dI' % (len(code) // 4), code)
    info = dx[name]
    off = info['ctab_offset_in_bytecode'] // 4
    ctab = words[off:off + info['ctab_dwords']]
    prof, legacy = profiles[name]
    w('// %s, %s, %s' % (name, prof, info['creator']))
    w('static const uint32_t %s_ctab[] = {' % name)
    for i in range(0, len(ctab), 8):
        w('    ' + ' '.join('0x%08x,' % x for x in ctab[i:i + 8]))
    w('};')
    w('static const Node %s_nodes[] = {' % name)
    for n in info['nodes']:
        w('    {"%s", %d, %d, %d, %d, %d, %d, %d, %d, %d},' % (
            n['path'], n['set'], n['reg'], n['count'], n['class'], n['type'], n['rows'], n['cols'],
            n['elements'], n['members']))
    w('};')
    w('static const Register %s_regs[] = {' % name)
    for kind in 'FIB':
        for r, v in sorted(sd[name][kind].items(), key=lambda x: int(x[0])):
            vals = ['0x' + x for x in v] + ['0'] * (4 - len(v))
            w('    {%d, %s, {%s}},' % (SETS[kind], r, ', '.join(vals)))
    w('};')
    w('')

w('static const Shader shaders[] = {')
for name in names:
    code = open(os.path.join(d, name + '.bin'), 'rb').read()
    ver = struct.unpack('<I', code[:4])[0]
    w('    {"%s", 0x%08x, %s_ctab, ARRAY_COUNT(%s_ctab), %s_nodes, ARRAY_COUNT(%s_nodes), %s_regs,' %
      (name, ver, name, name, name, name, name))
    w('     ARRAY_COUNT(%s_regs)},' % name)
w('};')
w('};    // namespace CTABTestData')

open(outpath, 'w', newline='\n').write('\n'.join(lines) + '\n')
print('wrote', outpath, len(lines), 'lines')
